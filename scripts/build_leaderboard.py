def generate(storage=None, production=False):
    source = (ROOT / 'content/leaderboard/release.json').read_bytes()
    if storage is None and (ROOT / 'content/leaderboard/storage.json').exists():
        storage = json.loads((ROOT / 'content/leaderboard/storage.json').read_text())
    snapshot = resolve_snapshot(json.loads(source), storage, production, hashlib.sha256(source).hexdigest())
    landing = leaderboard(snapshot)
    outputs = {ROOT / 'leaderboard/index.html': landing,
               ROOT / f'leaderboard/releases/{snapshot["id"]}/index.html': landing}
    task_map = {t['name']: t for t in snapshot['tasks']}
    for entry in snapshot['entries']:
        outputs[ROOT / f'leaderboard/entries/{entry["id"]}/index.html'] = entry_page(entry, snapshot)
        siblings = sorted([t for t in snapshot['trials'] if t['entry'] == entry['id']], key=lambda t: (task_map[t['task']]['hardware'],task_map[t['task']]['title']))
        for trial in siblings:
            outputs[ROOT / f'leaderboard/trials/{trial["id"]}/index.html'] = trial_page(trial, entry, snapshot, siblings)
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--production', action='store_true', help='Require verified, immutable Hugging Face data URLs')
    parser.add_argument('--storage', type=Path, help='Override the data-storage configuration (for local public-export previews)')
    args = parser.parse_args()
    changed = []
    storage = json.loads(args.storage.read_text()) if args.storage else None
    for path, content in generate(storage, args.production).items():
        if path.exists() and path.read_text() == content:
            continue
        changed.append(str(path.relative_to(ROOT)))
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if args.check and changed:
        raise SystemExit('Pages need rebuilding: ' + ', '.join(changed))
    print('Leaderboard pages are up to date.' if args.check else f'Generated {len(changed)} pages.')


if __name__ == '__main__':
    main()
