def esc(value):
    return html.escape(str(value), quote=True)


def number(value):
    if value is None:
        return '—'
    if abs(value) >= 1_000_000_000:
        return f'{value / 1_000_000_000:.2f}B'
    if abs(value) >= 1_000_000:
        return f'{value / 1_000_000:.1f}M'
    return f'{value:,.0f}'


def duration(value):
    if value is None:
        return '—'
    minutes = int(value // 60)
    if minutes == 0:
        return '<1min' if value > 0 else '0min'
    hours, minutes = divmod(minutes, 60)
    return f'{hours}h {minutes}min' if hours else f'{minutes}min'


def mean(values):
    return sum(values) / len(values) if values and all(v is not None for v in values) else None


def total(values):
    return sum(values) if values and all(v is not None for v in values) else None


def stats(trials):
    return {'score': mean([t['score'] for t in trials]),
            'tokens': total([t['tokens']['total_tokens'] for t in trials]),
            'seconds': mean([t['agent_seconds'] for t in trials])}


def score_cell(score):
    return f'<span class="score-value">{score:.1f}</span><span class="score-track" aria-hidden="true"><span style="width:{score}%"></span></span>'


