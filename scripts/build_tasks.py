"""Generate the task catalog and standalone pages from repository-local Markdown."""
from __future__ import annotations

import argparse
import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTENT = ROOT / "content" / "tasks"
TICK = chr(96)
TASK_NAME = re.compile(r"(?!all$)(?!task-)[a-z][a-z0-9]*(?:-[a-z0-9]+){0,4}")
GENERATED_MARKER = "<!-- Generated by scripts/build_tasks.py; edit content/tasks instead. -->"
STATUSES = {"setting", "draft", "planned"}
META_PATTERN = re.compile(r"^\* \*\*([^*]+)\*\*: (.*)$")
TOKEN_PATTERN = re.compile(
    TICK + r"([^" + TICK + r"]+)" + TICK
    + r"|\*\*(.+?)\*\*|\[([^\]]+)\]\(([^)\s]+)\)"
)


def esc(value: str) -> str:
    return html.escape(value, quote=True)


def inline(value: str) -> str:
    """Render the inline Markdown used by task settings, escaping raw HTML."""
    result, cursor = [], 0
    for match in TOKEN_PATTERN.finditer(value):
        result.append(esc(value[cursor:match.start()]))
        code, bold, label, url = match.groups()
        if code is not None:
            result.append(f"<code>{esc(code)}</code>")
        elif bold is not None:
            result.append(f"<strong>{inline(bold)}</strong>")
        elif url.startswith(("https://", "http://", "#", "./", "../")):
            result.append(f'<a href="{esc(url)}">{inline(label)}</a>')
        else:
            result.append(esc(match.group()))
        cursor = match.end()
    result.append(esc(value[cursor:]))
    return "".join(result)


def read_setting(task: dict) -> dict:
    source = CONTENT / f'{task["name"]}.md'
    lines = source.read_text(encoding="utf-8-sig").splitlines()
    if not lines or not lines[0].startswith("# "):
        raise ValueError(f"{source.name}: expected a Markdown title")
    title, metadata, preamble = lines[0][2:].strip(), {}, []
    index = 1
    while index < len(lines) and not lines[index].startswith("## "):
        match = META_PATTERN.match(lines[index])
        if match:
            metadata[match[1]] = match[2]
        else:
            preamble.append(lines[index])
        index += 1
    expected = f'search-swe/{task["name"]}'
    if metadata.get("Task name", "").strip(TICK) != expected:
        raise ValueError(f"{source.name}: Task name must be {expected}")
    if title != task["title"]:
        raise ValueError(f"{source.name}: title must match catalog title")
    if "Task type" in metadata:
        raise ValueError(f"{source.name}: unsupported metadata field: Task type")
    body, toc = markdown("\n".join(lines[index:]))
    intro, _ = markdown("\n".join(preamble))
    return {
        "title": title, "metadata": metadata, "intro": intro,
        "body": body, "toc": toc,
    }


def markdown(source: str) -> tuple[str, list[tuple[int, str, str]]]:
    """Headings, paragraphs, flat lists, and fenced code; no raw HTML execution."""
    lines, blocks, toc, used = source.splitlines(), [], [], {"overview"}
    index = 0

    def slug(text: str) -> str:
        base = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-") or "section"
        value, count = base, 2
        while value in used:
            value, count = f"{base}-{count}", count + 1
        used.add(value)
        return value

    def starts_block(line: str) -> bool:
        return bool(
            re.match(r"^#{2,3} ", line)
            or re.match(r"^(?:[-*]|\d+\.) ", line)
            or line.startswith(("~~~", TICK * 3))
        )

    while index < len(lines):
        line = lines[index]
        if not line.strip():
            index += 1
            continue
        if line.startswith(("~~~", TICK * 3)):
            fence, language = line[:3], line[3:].strip()
            code_lines = []
            index += 1
            while index < len(lines) and not lines[index].startswith(fence):
                code_lines.append(lines[index])
                index += 1
            if index == len(lines):
                raise ValueError("Unclosed Markdown code fence")
            language = re.sub(r"[^a-zA-Z0-9_-]", "", language)
            code = esc("\n".join(code_lines))
            blocks.append(f'<pre><code class="language-{language}">{code}</code></pre>')
            index += 1
            continue
        heading = re.match(r"^(#{2,3}) (.+)$", line)
        if heading:
            level, label = len(heading[1]), heading[2]
            anchor = slug(label)
            toc.append((level, anchor, label))
            blocks.append(f'<h{level} id="{anchor}">{inline(label)}</h{level}>')
            index += 1
            continue
        item = re.match(r"^([-*]|\d+\.) (.+)$", line)
        if item:
            ordered = item[1][0].isdigit()
            tag, items = ("ol" if ordered else "ul"), []
            while index < len(lines):
                match = re.match(r"^([-*]|\d+\.) (.+)$", lines[index])
                if not match or match[1][0].isdigit() != ordered:
                    break
                items.append(f"<li>{inline(match[2])}</li>")
                index += 1
            blocks.append(f"<{tag}>" + "".join(items) + f"</{tag}>")
            continue
        paragraph = [line.strip()]
        index += 1
        while index < len(lines) and lines[index].strip() and not starts_block(lines[index]):
            paragraph.append(lines[index].strip())
            index += 1
        blocks.append("<p>" + inline(" ".join(paragraph)) + "</p>")
    return "\n".join(blocks), toc


def header(prefix: str) -> str:
    return f"""<a class="skip-link" href="#main-content">Skip to content</a>
<header class="home-header">
  <div class="home-header-inner">
    <a class="home-brand" href="{prefix or './'}" aria-label="Search-SWE home">
      <img src="{prefix}assets/logo.png" width="32" height="32" alt="" />
      <span>Search-SWE</span>
    </a>
    <nav class="home-nav" aria-label="Main navigation">
      <a href="{prefix or './'}">Overview</a>
      <a href="{prefix}tasks/" aria-current="{('page' if not prefix else 'true')}">Tasks</a>
      <a href="https://github.com/VectorSpaceLab/Search-SWE" target="_blank" rel="noreferrer">GitHub <span aria-hidden="true">↗</span></a>
    </nav>
  </div>
</header>"""


def footer() -> str:
    return """<footer class="home-footer">
  <span>Search-SWE · VectorSpaceLab</span>
  <a href="#top">Back to top ↑</a>
</footer>"""


def document(title: str, description: str, prefix: str, body: str) -> str:
    return f"""<!doctype html>
{GENERATED_MARKER}
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <meta name="description" content="{esc(description)}" />
  <meta name="theme-color" content="#ffffff" />
  <title>{esc(title)} — Search-SWE</title>
  <link rel="icon" type="image/png" href="{prefix}assets/logo.png" />
  <link rel="apple-touch-icon" href="{prefix}assets/logo.png" />
  <link rel="stylesheet" href="{prefix}home-sections.css?v=3" />
  <link rel="stylesheet" href="{prefix}task-pages.css?v=4" />
</head>
<body id="top">
{header(prefix)}
{body}
</body>
</html>
"""


def task_icon() -> str:
    return '<svg viewBox="0 0 24 24" width="20" height="20" fill="none" stroke="currentColor" stroke-width="1.7" stroke-linecap="round" aria-hidden="true" focusable="false"><circle cx="10" cy="10" r="6"/><path d="m15 15 6 6"/></svg>'


def home_card(task: dict) -> str:
    return f"""            <li>
              <a class="home-task" href="tasks/{task['name']}/">
                <span class="home-task-icon">{task_icon()}</span>
                <span class="home-task-copy">
                  <span class="home-task-title">{esc(task['title'])}</span>
                  <span class="home-task-summary">{esc(task.get('homepageSummary', task['summary']))}</span>
                </span>
                <span class="home-task-arrow" aria-hidden="true">→</span>
              </a>
            </li>"""


def catalog_card(task: dict) -> str:
    return f"""<li id="{task['name']}">
  <a class="catalog-task" href="{task['name']}/">
    <span class="home-task-icon">{task_icon()}</span>
    <span class="home-task-copy">
      <span class="home-task-title">{esc(task['title'])}</span>
      <span class="home-task-summary">{esc(task['summary'])}</span>
      <span class="home-task-topic">{esc(task['tag'])}</span>
    </span>
    <span class="home-task-arrow" aria-hidden="true">→</span>
  </a>
</li>"""


def catalog_page(tasks: list[dict]) -> str:
    cards = "\n".join(catalog_card(task) for task in tasks)
    count = f'{len(tasks)} task' + ('s' if len(tasks) != 1 else '')
    return document("Task catalog", "Browse Search-SWE tasks for implementing and optimizing search systems.", "../", f"""
<div class="home-layout">
  <aside class="home-sidebar catalog-sidebar">{directory(tasks)}</aside>
  <main id="main-content" class="home-document">
    <header class="home-intro catalog-intro">
      <h1>Tasks</h1>
      <p>Build and improve search systems under fixed resource constraints. Browse each task's goal, inputs, submission interface, and evaluation criteria.</p>
    </header>
    <section class="home-section" aria-labelledby="all-tasks-title">
      <div class="home-section-heading"><h2 id="all-tasks-title">All tasks</h2><span class="catalog-count">{count}</span></div>
      <ul class="home-task-list">{cards}</ul>
    </section>
    {footer()}
  </main>
</div>""")


def directory(tasks: list[dict], current: dict | None = None) -> str:
    links = []
    for task in tasks:
        active = ' aria-current="page"' if current and task["name"] == current["name"] else ""
        href = f'../{task["name"]}/' if current else f'#{task["name"]}'
        links.append(f'<a href="{href}"{active}><span class="task-directory-title">{esc(task.get("navTitle", task["title"]))}</span></a>')
    return '<nav aria-label="Task directory"><div class="task-directory-group"><p>All tasks</p>' + "".join(links) + "</div></nav>"


def contents(toc: list[tuple[int, str, str]]) -> str:
    items = ['<a href="#overview">Overview</a>']
    for level, anchor, label in toc:
        klass = ' class="toc-subsection"' if level == 3 else ""
        items.append(f'<a href="#{anchor}"{klass}>{esc(label)}</a>')
    return "".join(items)


def detail_page(task: dict, tasks: list[dict], setting: dict) -> str:
    metadata = setting["metadata"]
    facts = "".join(
        f"<div><dt>{esc(label)}</dt><dd>{inline(metadata.get(label, 'To be specified'))}</dd></div>"
        for label in ("Domain", "Primary focus", "Primary metric")
    )
    tags = re.findall(TICK + "([^" + TICK + "]+)" + TICK, metadata.get("Tags", ""))
    tags_html = "".join(f"<span>{esc(tag)}</span>" for tag in tags)
    page_toc = contents(setting["toc"])
    current_index = tasks.index(task)
    adjacent = []
    for offset, label in ((-1, "Previous task"), (1, "Next task")):
        index = current_index + offset
        if 0 <= index < len(tasks):
            neighbor = tasks[index]
            adjacent.append(f'<a href="../{neighbor["name"]}/"><span>{label}</span><strong>{esc(neighbor["title"])}</strong></a>')
    return document(setting["title"], task["summary"], "../../", f"""
<main id="main-content" class="task-reader">
  <nav class="task-breadcrumbs" aria-label="Breadcrumb"><a href="../../">Home</a><span aria-hidden="true">/</span><a href="../../tasks/">Tasks</a><span aria-hidden="true">/</span><span aria-current="page">{esc(task['name'])}</span></nav>
  <div class="task-reader-layout">
    <aside class="task-directory"><a class="all-tasks-link" href="../../tasks/">← All tasks</a>{directory(tasks, task)}</aside>
    <article class="task-article">
      <header id="overview" class="task-article-header">
        <div class="task-article-kicker"><span>{esc(task['name'])}</span></div>
        <h1>{esc(setting['title'])}</h1>
        <div class="task-summary">{setting['intro']}</div>
        <dl class="task-specs">{facts}</dl>
        <div class="task-tags" aria-label="Task topics">{tags_html}</div>
      </header>
      <details class="task-mobile-toc"><summary>On this page</summary><nav aria-label="Page contents">{page_toc}</nav></details>
      <div class="task-prose">{setting['body']}</div>
      <nav class="task-adjacent" aria-label="Adjacent tasks">{"".join(adjacent)}</nav>
      {footer()}
    </article>
    <aside class="task-toc"><nav aria-label="On this page"><p>On this page</p>{page_toc}</nav></aside>
  </div>
</main>""")


def generate() -> dict[Path, str]:
    tasks = json.loads((CONTENT / "catalog.json").read_text(encoding="utf-8"))
    if not isinstance(tasks, list) or not tasks:
        raise ValueError("Catalog must be a nonempty list of tasks")
    names = []
    for task in tasks:
        if not isinstance(task, dict) or not isinstance(task.get("name"), str) or not TASK_NAME.fullmatch(task["name"]):
            raise ValueError("Invalid task name: use at most five lowercase hyphen-separated words; omit task-; all is reserved")
        names.append(task["name"])
        if "mode" in task or "id" in task:
            raise ValueError("Catalog entries use name for task identity; unsupported fields: mode, id")
        if task.get("status") not in STATUSES:
            raise ValueError("Unknown task status")
        for field in ("title", "summary", "tag"):
            if not isinstance(task.get(field), str) or not task[field].strip():
                raise ValueError(f"{task['name']}: missing {field}")
        if "featured" in task and not isinstance(task["featured"], bool):
            raise ValueError("featured must be a boolean")
    if len(names) != len(set(names)):
        raise ValueError("Duplicate task names")
    outputs = {ROOT / "tasks" / "index.html": catalog_page(tasks)}
    for task in tasks:
        outputs[ROOT / "tasks" / task["name"] / "index.html"] = detail_page(task, tasks, read_setting(task))
    homepage = (ROOT / "index.html").read_text(encoding="utf-8")
    start, end = "<!-- TASK_CARDS:START -->", "<!-- TASK_CARDS:END -->"
    if (homepage.count(start) != 1 or homepage.count(end) != 1
            or homepage.index(start) > homepage.index(end)):
        raise ValueError("Homepage must have one TASK_CARDS marker pair")
    cards = "\n".join(home_card(task) for task in tasks if task.get("featured"))
    block = start + '\n          <ul class="home-task-list" aria-label="Selected tasks">\n' + cards + "\n          </ul>\n          " + end
    outputs[ROOT / "index.html"] = homepage[:homepage.index(start)] + block + homepage[homepage.index(end) + len(end):]
    return {path: "\n".join(line.rstrip() for line in content.splitlines()) + "\n" for path, content in outputs.items()}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated pages need updating.")
    parser.add_argument("--catalog-only", action="store_true", help="Update or check only the task catalog and homepage cards.")
    args = parser.parse_args()
    changed = []
    outputs = generate()
    if args.catalog_only:
        outputs = {path: content for path, content in outputs.items() if path in (ROOT / "tasks" / "index.html", ROOT / "index.html")}
    for path, content in outputs.items():
        existing = path.read_text(encoding="utf-8") if path.exists() else None
        if existing == content:
            continue
        changed.append(str(path.relative_to(ROOT)))
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    if not args.catalog_only:
        for path in sorted((ROOT / "tasks").glob("*/index.html")):
            if path not in outputs and GENERATED_MARKER in path.read_text(encoding="utf-8"):
                changed.append(f"{path.relative_to(ROOT)} (obsolete)")
                if not args.check:
                    path.unlink()
                    if not any(path.parent.iterdir()):
                        path.parent.rmdir()
    if args.check and changed:
        print("Pages need regenerating:\n" + "\n".join(changed))
        return 1
    print("Task pages are up to date." if args.check else f"Generated {len(changed)} updated pages.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
